CREATE TABLE ORGANIZACAO (
  ID      VARCHAR2(64)  PRIMARY KEY,
  NOME    VARCHAR2(80)  NOT NULL,
  SIGLA   VARCHAR2(3)   NOT NULL,
  MATIZ   NUMBER(3)     NOT NULL CHECK (MATIZ BETWEEN 0 AND 360)
);

CREATE TABLE USUARIO (
  ID              VARCHAR2(64)  PRIMARY KEY,
  NOME            VARCHAR2(80)  NOT NULL,
  EMAIL           VARCHAR2(120) NOT NULL CONSTRAINT UQ_USUARIO_EMAIL UNIQUE,
  SENHA_HASH      VARCHAR2(200) NOT NULL,
  PAPEL           VARCHAR2(12)  NOT NULL CHECK (PAPEL IN ('organizador', 'espectador')),
  ID_ORGANIZACAO  VARCHAR2(64)  REFERENCES ORGANIZACAO (ID)
);

CREATE TABLE TORNEIO (
  ID              VARCHAR2(64)   PRIMARY KEY,
  NOME            VARCHAR2(120)  NOT NULL,
  DESCRICAO       VARCHAR2(1000) NOT NULL,
  ID_ORGANIZACAO  VARCHAR2(64)   NOT NULL REFERENCES ORGANIZACAO (ID),
  ID_ORGANIZADOR  VARCHAR2(64)   NOT NULL REFERENCES USUARIO (ID),
  VISIBILIDADE    VARCHAR2(7)    NOT NULL CHECK (VISIBILIDADE IN ('publico', 'privado')),
  CODIGO_ACESSO   VARCHAR2(40),
  STATUS          VARCHAR2(12)   NOT NULL CHECK (STATUS IN ('criacao', 'publicado', 'chaveamento', 'andamento', 'finalizado', 'cancelado')),
  DATA_INICIO     DATE           NOT NULL,
  DATA_FIM        DATE           NOT NULL,
  CIDADE          VARCHAR2(120)  NOT NULL,
  NOME_LOCAL      VARCHAR2(120)  NOT NULL,
  CAPA_1          VARCHAR2(7)    NOT NULL,
  CAPA_2          VARCHAR2(7)    NOT NULL,
  CRIADO_EM_MS    NUMBER(15)     NOT NULL,
  CONSTRAINT CK_TORNEIO_PERIODO CHECK (DATA_FIM >= DATA_INICIO),
  CONSTRAINT CK_TORNEIO_CODIGO CHECK (VISIBILIDADE = 'publico' OR CODIGO_ACESSO IS NOT NULL)
);
CREATE INDEX IX_TORNEIO_ORGANIZADOR ON TORNEIO (ID_ORGANIZADOR);

-- quadras/espaços e árbitros do torneio (listas ordenadas)
CREATE TABLE TORNEIO_LOCAL (
  ID_TORNEIO  VARCHAR2(64) NOT NULL REFERENCES TORNEIO (ID) ON DELETE CASCADE,
  ORDEM       NUMBER(3)    NOT NULL,
  NOME        VARCHAR2(60) NOT NULL,
  PRIMARY KEY (ID_TORNEIO, ORDEM)
);

CREATE TABLE TORNEIO_ARBITRO (
  ID_TORNEIO  VARCHAR2(64) NOT NULL REFERENCES TORNEIO (ID) ON DELETE CASCADE,
  ORDEM       NUMBER(3)    NOT NULL,
  NOME        VARCHAR2(80) NOT NULL,
  PRIMARY KEY (ID_TORNEIO, ORDEM)
);

CREATE TABLE TIMES (
  ID          VARCHAR2(64) PRIMARY KEY,
  ID_TORNEIO  VARCHAR2(64) NOT NULL REFERENCES TORNEIO (ID) ON DELETE CASCADE,
  ORDEM       NUMBER(4)    NOT NULL,
  NOME        VARCHAR2(80) NOT NULL,
  SIGLA       VARCHAR2(4)  NOT NULL,
  COR         VARCHAR2(7)  NOT NULL,
  TECNICO     VARCHAR2(80) NOT NULL
);
CREATE INDEX IX_TIMES_TORNEIO ON TIMES (ID_TORNEIO);

CREATE TABLE JOGADORES (
  ID             VARCHAR2(64) PRIMARY KEY,
  ID_TIME        VARCHAR2(64) NOT NULL REFERENCES TIMES (ID) ON DELETE CASCADE,
  ORDEM          NUMBER(3)    NOT NULL,
  NOME           VARCHAR2(80) NOT NULL,
  APELIDO        VARCHAR2(40),
  NUMERO_CAMISA  NUMBER(2)    NOT NULL CHECK (NUMERO_CAMISA BETWEEN 0 AND 99)
);

CREATE TABLE MODALIDADE (
  ID                   VARCHAR2(64) PRIMARY KEY,
  ID_TORNEIO           VARCHAR2(64) NOT NULL REFERENCES TORNEIO (ID) ON DELETE CASCADE,
  ORDEM                NUMBER(2)    NOT NULL,
  ESPORTE              VARCHAR2(60) NOT NULL,
  TIPO_SUMULA          VARCHAR2(9)  NOT NULL CHECK (TIPO_SUMULA IN ('pontos', 'set', 'colocacao')),
  CATEGORIA            VARCHAR2(5)  NOT NULL CHECK (CATEGORIA IN ('M', 'F', 'Misto')),
  SUBMODALIDADE        VARCHAR2(60),
  FORMATO              VARCHAR2(16) NOT NULL CHECK (FORMATO IN ('eliminacao', 'dupla_eliminacao', 'grupos_mata', 'pontos_corridos', 'prova')),
  CLASSIFICADOS_GRUPO  NUMBER(1),
  QTD_GRUPOS           NUMBER(1),
  RETURNO              NUMBER(1)    CHECK (RETURNO IN (0, 1))
);
CREATE INDEX IX_MODALIDADE_TORNEIO ON MODALIDADE (ID_TORNEIO);

-- espaços adequados à modalidade (ex.: natação só na piscina); vazio = todos do torneio
CREATE TABLE MODALIDADE_LOCAL (
  ID_MODALIDADE  VARCHAR2(64) NOT NULL REFERENCES MODALIDADE (ID) ON DELETE CASCADE,
  ORDEM          NUMBER(3)    NOT NULL,
  NOME           VARCHAR2(60) NOT NULL,
  PRIMARY KEY (ID_MODALIDADE, ORDEM)
);

-- inscrição de um time numa modalidade (ORDEM_CABECA preenchida = cabeça de chave nº)
CREATE TABLE PARTICIPACAO (
  ID_MODALIDADE  VARCHAR2(64) NOT NULL REFERENCES MODALIDADE (ID) ON DELETE CASCADE,
  ID_TIME        VARCHAR2(64) NOT NULL REFERENCES TIMES (ID),
  ORDEM          NUMBER(3)    NOT NULL,
  ORDEM_CABECA   NUMBER(3),
  PRIMARY KEY (ID_MODALIDADE, ID_TIME)
);

CREATE TABLE GRUPO (
  ID             VARCHAR2(64) PRIMARY KEY,
  ID_MODALIDADE  VARCHAR2(64) NOT NULL REFERENCES MODALIDADE (ID) ON DELETE CASCADE,
  ORDEM          NUMBER(2)    NOT NULL,
  NOME           VARCHAR2(40) NOT NULL
);

CREATE TABLE GRUPO_TIME (
  ID_GRUPO  VARCHAR2(64) NOT NULL REFERENCES GRUPO (ID) ON DELETE CASCADE,
  ORDEM     NUMBER(3)    NOT NULL,
  ID_TIME   VARCHAR2(64) NOT NULL REFERENCES TIMES (ID),
  PRIMARY KEY (ID_GRUPO, ID_TIME)
);

CREATE TABLE PARTIDA (
  ID                  VARCHAR2(64) PRIMARY KEY,
  ID_MODALIDADE       VARCHAR2(64) NOT NULL REFERENCES MODALIDADE (ID) ON DELETE CASCADE,
  ORDEM               NUMBER(4)    NOT NULL,
  FASE                VARCHAR2(40) NOT NULL,
  RODADA              NUMBER(3)    NOT NULL,
  POSICAO             NUMBER(3)    NOT NULL,
  ID_GRUPO            VARCHAR2(64) REFERENCES GRUPO (ID),
  ID_TIME_A           VARCHAR2(64) REFERENCES TIMES (ID),
  ID_TIME_B           VARCHAR2(64) REFERENCES TIMES (ID),
  ROTULO_A            VARCHAR2(60),
  ROTULO_B            VARCHAR2(60),
  -- para onde vai o vencedor / o perdedor (dupla eliminação); verificadas no fim da transação
  PROX_PARTIDA        VARCHAR2(64) CONSTRAINT FK_PARTIDA_PROX REFERENCES PARTIDA (ID) DEFERRABLE INITIALLY DEFERRED,
  PROX_LADO           CHAR(1)      CHECK (PROX_LADO IN ('a', 'b')),
  CHAVE               CHAR(1)      CHECK (CHAVE IN ('W', 'L', 'F')),
  PROX_PERDEDOR       VARCHAR2(64) CONSTRAINT FK_PARTIDA_PROX_PERD REFERENCES PARTIDA (ID) DEFERRABLE INITIALLY DEFERRED,
  PROX_PERDEDOR_LADO  CHAR(1)      CHECK (PROX_PERDEDOR_LADO IN ('a', 'b')),
  ESTAGIO             NUMBER(3),
  -- classificado de grupo que ocupará o lado A/B no mata-mata
  ORIGEM_A_GRUPO      VARCHAR2(64) REFERENCES GRUPO (ID) DEFERRABLE INITIALLY DEFERRED,
  ORIGEM_A_LUGAR      NUMBER(2),
  ORIGEM_B_GRUPO      VARCHAR2(64) REFERENCES GRUPO (ID) DEFERRABLE INITIALLY DEFERRED,
  ORIGEM_B_LUGAR      NUMBER(2),
  BYE                 NUMBER(1)    CHECK (BYE = 1),
  STATUS              VARCHAR2(9)  NOT NULL CHECK (STATUS IN ('agendada', 'ao_vivo', 'encerrada')),
  DATA_PARTIDA        DATE,
  HORA                VARCHAR2(5),
  LOCAL_PARTIDA       VARCHAR2(60),
  ARBITRO             VARCHAR2(80),
  FIXADA              NUMBER(1)    CHECK (FIXADA = 1)
);
CREATE INDEX IX_PARTIDA_MODALIDADE ON PARTIDA (ID_MODALIDADE);
-- consultas de conflito de agenda (RF04): mesmo dia/horário e local ou árbitro
CREATE INDEX IX_PARTIDA_AGENDA ON PARTIDA (DATA_PARTIDA, HORA, LOCAL_PARTIDA);

-- participantes de uma prova (súmula de colocação)
CREATE TABLE PARTIDA_PARTICIPANTE (
  ID_PARTIDA  VARCHAR2(64) NOT NULL REFERENCES PARTIDA (ID) ON DELETE CASCADE,
  ORDEM       NUMBER(3)    NOT NULL,
  ID_TIME     VARCHAR2(64) NOT NULL REFERENCES TIMES (ID),
  PRIMARY KEY (ID_PARTIDA, ORDEM)
);

-- súmula: generalização disjunta por TIPO
CREATE TABLE SUMULA (
  ID_PARTIDA  VARCHAR2(64) PRIMARY KEY REFERENCES PARTIDA (ID) ON DELETE CASCADE,
  TIPO        VARCHAR2(9)  NOT NULL CHECK (TIPO IN ('pontos', 'set', 'colocacao'))
);

CREATE TABLE SUMULA_PONTOS (
  ID_PARTIDA   VARCHAR2(64) PRIMARY KEY REFERENCES SUMULA (ID_PARTIDA) ON DELETE CASCADE,
  PONTUACAO_A  NUMBER(4)    NOT NULL CHECK (PONTUACAO_A >= 0),
  PONTUACAO_B  NUMBER(4)    NOT NULL CHECK (PONTUACAO_B >= 0),
  PENALTIS_A   NUMBER(3),
  PENALTIS_B   NUMBER(3)
);

CREATE TABLE SUMULA_SET (
  ID_PARTIDA   VARCHAR2(64) NOT NULL REFERENCES SUMULA (ID_PARTIDA) ON DELETE CASCADE,
  NUM_SET      NUMBER(2)    NOT NULL,
  PONTUACAO_A  NUMBER(3)    NOT NULL CHECK (PONTUACAO_A >= 0),
  PONTUACAO_B  NUMBER(3)    NOT NULL CHECK (PONTUACAO_B >= 0),
  PRIMARY KEY (ID_PARTIDA, NUM_SET)
);

CREATE TABLE SUMULA_COLOCACAO (
  ID_PARTIDA  VARCHAR2(64) NOT NULL REFERENCES SUMULA (ID_PARTIDA) ON DELETE CASCADE,
  ORDEM       NUMBER(3)    NOT NULL,
  ID_TIME     VARCHAR2(64) NOT NULL,
  TEMPO_MS    NUMBER(10)   NOT NULL CHECK (TEMPO_MS > 0),
  PRIMARY KEY (ID_PARTIDA, ORDEM)
);

-- advertência/cartão por jogador e partida
CREATE TABLE CARTAO (
  ID_PARTIDA  VARCHAR2(64) NOT NULL REFERENCES SUMULA (ID_PARTIDA) ON DELETE CASCADE,
  ORDEM       NUMBER(3)    NOT NULL,
  ID_TIME     VARCHAR2(64) NOT NULL,
  ID_JOGADOR  VARCHAR2(64) NOT NULL,
  COR         VARCHAR2(8)  NOT NULL CHECK (COR IN ('amarelo', 'vermelho')),
  MINUTO      NUMBER(3)    NOT NULL CHECK (MINUTO >= 0),
  PRIMARY KEY (ID_PARTIDA, ORDEM)
);

CREATE TABLE PREMIO (
  ID             VARCHAR2(64)  PRIMARY KEY,
  ID_TORNEIO     VARCHAR2(64)  NOT NULL REFERENCES TORNEIO (ID) ON DELETE CASCADE,
  ORDEM          NUMBER(3)     NOT NULL,
  NOME           VARCHAR2(120) NOT NULL,
  TIPO           VARCHAR2(10)  NOT NULL CHECK (TIPO IN ('coletivo', 'individual')),
  VALOR          NUMBER(12, 2) CHECK (VALOR >= 0),
  COLOCACAO      NUMBER(2)     NOT NULL,
  ID_MODALIDADE  VARCHAR2(64),
  CONTEMPLADO    VARCHAR2(120)
);

CREATE TABLE FAVORITO (
  ID_USUARIO  VARCHAR2(64) NOT NULL REFERENCES USUARIO (ID) ON DELETE CASCADE,
  ID_TORNEIO  VARCHAR2(64) NOT NULL REFERENCES TORNEIO (ID) ON DELETE CASCADE,
  PRIMARY KEY (ID_USUARIO, ID_TORNEIO)
);

-- torneios privados liberados por código para cada usuário
CREATE TABLE ACESSO_TORNEIO (
  ID_USUARIO   VARCHAR2(64) NOT NULL REFERENCES USUARIO (ID) ON DELETE CASCADE,
  ID_TORNEIO   VARCHAR2(64) NOT NULL REFERENCES TORNEIO (ID) ON DELETE CASCADE,
  LIBERADO_EM  TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  PRIMARY KEY (ID_USUARIO, ID_TORNEIO)
);
