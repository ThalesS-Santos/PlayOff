--   * TORNEIO separa VISIBILIDADE (publico/privado) de STATUS (ciclo de vida)
--   * PARTICIPACAO liga o time à modalidade (com a ordem de cabeça de chave)
--   * MODALIDADE pertence a um torneio (substitui TORNEIO_MODALIDADE)
--   * súmula como generalização: SUMULA + SUMULA_PONTOS / SUMULA_SET / SUMULA_COLOCACAO
--   * CARTAO guarda time e jogador sem FK: o histórico sobrevive a mudanças no elenco
--
-- Execute conectado com o usuário da aplicação (ver db/README.md).
-- Para recriar do zero, rode antes o db/000_drop.sql.
